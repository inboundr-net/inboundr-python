"""Keeps the SDK's types in step with the platform's API description.

    python scripts/spec.py sync    copy openapi.yaml from the platform, regenerate types
    python scripts/spec.py types   regenerate src/inboundr/_generated/api.py
    python scripts/spec.py check   exit 1 if the generated types are stale (run in CI)

`sync` reads INBOUNDR_SPEC (a path or an https URL), defaulting to a sibling
checkout of the platform at ../inbound-app.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "openapi" / "openapi.yaml"
TYPES = ROOT / "src" / "inboundr" / "_generated" / "api.py"
HEADER = '"""GENERATED by `python scripts/spec.py types` from openapi/openapi.yaml. Do not edit."""\n\n'


def generate(out: Path) -> None:
    subprocess.run(
        [
            sys.executable, "-m", "datamodel_code_generator",
            "--input", str(SPEC),
            "--input-file-type", "openapi",
            "--output-model-type", "typing.TypedDict",
            "--target-python-version", "3.10",
            "--use-standard-collections",
            "--use-union-operator",
            "--enum-field-as-literal", "all",
            "--use-schema-description",
            "--disable-timestamp",
            "--formatters", "builtin",
            "--output", str(out),
        ],
        check=True,
        stderr=subprocess.DEVNULL,
    )
    body = out.read_text()
    # Drop the generator's own banner, which names a temp path on check runs.
    lines = [line for line in body.splitlines(keepends=True) if not line.startswith("#")]
    out.write_text(HEADER + "".join(lines).lstrip("\n"))


def sync() -> None:
    source = os.environ.get("INBOUNDR_SPEC", str(ROOT.parent / "inbound-app" / "openapi" / "openapi.yaml"))
    if source.startswith(("http://", "https://")):
        with urllib.request.urlopen(source) as response:  # noqa: S310 (fixed, user-supplied URL)
            SPEC.write_bytes(response.read())
    else:
        shutil.copyfile(source, SPEC)
    print(f"spec: copied {source}")
    generate(TYPES)
    print("spec: regenerated src/inboundr/_generated/api.py")


def check() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "api.py"
        generate(out)
        if out.read_text() != TYPES.read_text():
            print("src/inboundr/_generated/api.py is stale. Run `python scripts/spec.py types`.", file=sys.stderr)
            return 1
    print("spec: generated types are up to date")
    return 0


if __name__ == "__main__":
    mode = sys.argv[1] if len(sys.argv) > 1 else ""
    if mode == "sync":
        sync()
    elif mode == "types":
        generate(TYPES)
    elif mode == "check":
        sys.exit(check())
    else:
        print("usage: python scripts/spec.py sync|types|check", file=sys.stderr)
        sys.exit(2)
